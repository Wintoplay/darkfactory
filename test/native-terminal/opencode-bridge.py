#!/usr/bin/env python3
"""Test-only bridge from a disposable DarkFactory PTY to native Ghostty.

This is an output probe, not an interactive client or a security adapter.
"""
import fcntl
import http.client
import json
import os
from pathlib import Path
import re
import select
import struct
import sys
import termios
import time
import tty
from urllib.parse import urlsplit

base = urlsplit(os.environ['DFB_BASE'])
if base.scheme != 'http' or base.hostname != '127.0.0.1':
    raise SystemExit('only the isolated loopback daemon is supported')
sid, token = os.environ['DFB_SID'], os.environ['DFB_TOKEN']
result_path = Path(os.environ['DFB_NATIVE_RESULT'])
headers = {'Authorization': 'Bearer ' + token, 'X-DF-Request': '1'}
prefix = '/api/v1/sessions/' + sid
result = {'ok': False, 'synthetic': True, 'measurement': 'post start to Ghostty cursor-position reply',
          'workload': '162k ascii PTY burst', 'bytes': 0}
old = termios.tcgetattr(sys.stdin.fileno())

def write_all(data):
    view = memoryview(data)
    while view:
        count = os.write(sys.stdout.fileno(), view)
        if count <= 0:
            raise RuntimeError('native terminal output did not accept data')
        view = view[count:]


def post(path, body, content_type):
    conn = http.client.HTTPConnection(base.hostname, base.port, timeout=10)
    conn.request('POST', prefix + path, body=body, headers={**headers, 'Content-Type': content_type})
    response = conn.getresponse()
    response.read()
    status = response.status
    conn.close()
    if status != 204:
        raise RuntimeError(f'{path} returned HTTP {status}')

try:
    tty.setraw(sys.stdin.fileno())
    rows, cols, _, _ = struct.unpack('HHHH', fcntl.ioctl(sys.stdin, termios.TIOCGWINSZ, bytes(8)))
    if not rows or not cols:
        raise RuntimeError('terminal did not report a size')
    conn = http.client.HTTPConnection(base.hostname, base.port, timeout=15)
    conn.request('GET', prefix + '/stream', headers=headers)
    response = conn.getresponse()
    if response.status != 200:
        raise RuntimeError(f'stream returned HTTP {response.status}')
    result.update(cols=cols, rows=rows, redraw=response.getheader('X-DF-Redraw') == '1')
    post('/resize', json.dumps({'cols': cols, 'rows': rows}), 'application/json')
    if result['redraw']:
        post('/redraw', '', 'text/plain')
    # Allow the isolated OpenCode UI to finish starting, then type without
    # submitting a prompt. The terminal stream must contain that exact text.
    time.sleep(4)
    command = b'qzxvjkmbprwytfgh'
    marker = command
    result['workload'] = 'OpenCode TUI input, no submitted prompt'
    start = time.monotonic()
    post('/input', command, 'text/plain')
    recent = b''
    found = False
    deadline = time.monotonic() + 15
    while time.monotonic() < deadline:
        chunk = response.read1(32768)
        if not chunk:
            raise RuntimeError('stream ended before marker')
        result['bytes'] += len(chunk)
        write_all(chunk)
        combined = recent + chunk
        if marker in combined:
            found = True
            break
        recent = combined[-len(marker):]
    if not found:
        raise RuntimeError('marker timeout')
    result['markerReadMs'] = round((time.monotonic() - start) * 1000, 1)
    # The CPR reply is generated by the native emulator after it processes the
    # preceding bytes. It does not establish that pixels were presented.
    termios.tcflush(sys.stdin.fileno(), termios.TCIFLUSH)
    write_all(b'\x1b[6n')
    answer = b''
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        ready, _, _ = select.select([sys.stdin.fileno()], [], [], max(0, deadline - time.monotonic()))
        if not ready:
            break
        answer += os.read(sys.stdin.fileno(), 4096)
        if re.search(rb'\x1b\[[0-9]+;[0-9]+R', answer):
            result['parsedMs'] = round((time.monotonic() - start) * 1000, 1)
            result['ok'] = True
            break
    if not result['ok']:
        raise RuntimeError('native terminal did not answer cursor-position query')
except Exception as exc:
    result['error'] = str(exc)
finally:
    termios.tcsetattr(sys.stdin.fileno(), termios.TCSADRAIN, old)
    result_path.write_text(json.dumps(result) + '\n')
    os.chmod(result_path, 0o600)
sys.exit(0 if result['ok'] else 1)
